import assert from 'node:assert/strict';
import { answerQuestion, phaseAt, roomView, RoomError } from '../lib/rooms/engine';
import type { RoomState } from '../lib/rooms/types';
const state: RoomState = { version: 1, title: 'Test', hostId: 'a', settings: { level: 'all', questionCount: 5, secondsPerQuestion: 10 }, players: [{ id: 'a', name: 'A', ready: true, left: false }, { id: 'b', name: 'B', ready: true, left: false }], questions: Array.from({ length: 5 }, () => ({ word: 'test', choices: ['A','B','C','D'], correctIndex: 2 })), startedAt: null, closed: false, answers: {} };
assert.equal(phaseAt(state, 1000).phase, 'waiting');
assert.throws(() => roomView('ABC234', state, 'outsider', 1000), RoomError);
state.startedAt = 2000;
assert.equal(phaseAt(state, 1000).phase, 'countdown');
assert.equal(phaseAt(state, 2000).phase, 'question');
assert(!JSON.stringify(roomView('ABC234', state, 'a', 2000)).includes('correctIndex'));
answerQuestion(state, 'a', 0, 2, 2000);
assert.equal(state.answers[0].a.points, 150);
assert.equal(roomView('ABC234', state, 'a', 2001).players.find(p => p.id === 'a')!.score, 0, 'Current scores cannot reveal the correct choice early');
assert.throws(() => answerQuestion(state, 'a', 0, 1, 2001), RoomError);
assert.throws(() => answerQuestion(state, 'b', 1, 0, 2001), RoomError);
assert.throws(() => answerQuestion(state, 'outsider', 0, 2, 2001), RoomError);
answerQuestion(state, 'b', 0, 0, 2100);
assert.equal(state.answers[0].b.points, 0);
assert.equal(roomView('ABC234', state, 'a', 12000).question!.correctIndex, 2);
assert.equal(roomView('ABC234', state, 'a', 12000).players[0].score, 150);
assert.throws(() => answerQuestion(state, 'b', 0, 2, 12000), RoomError);
assert.equal(phaseAt(state, 15000).index, 1);
assert.equal(phaseAt(state, 67000).phase, 'finished');
state.closed = true;
assert.equal(phaseAt(state, 1000).phase, 'closed');
const longRoom: RoomState = { ...state, closed: false, settings: { ...state.settings, questionCount: 50 }, questions: Array.from({ length: 50 }, () => state.questions[0]), answers: {} };
const lastQuestionTime = 2000 + 49 * 13000;
assert.equal(phaseAt(longRoom, lastQuestionTime).index, 49);
answerQuestion(longRoom, 'a', 49, 2, lastQuestionTime);
assert.equal(longRoom.answers[49].a.points, 150);
assert.equal(phaseAt(longRoom, 2000 + 50 * 13000).phase, 'finished');
console.log('Room engine: phases, private answers, scoring, duplicate/late answers and membership passed.');
