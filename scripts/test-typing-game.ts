import assert from 'node:assert/strict';
import { newTypingGame, normalizeTyping, typeIntoGame, typingTick, TYPING_DURATION, type TypingWord } from '../lib/typing-game';
const pool: TypingWord[] = ['cat', 'car', 'bird', 'train', 'apple'].map((word, id) => ({ id, word, meaning: word }));
let state = typingTick(newTypingGame(), 100, pool);
assert.equal(state.targets.length, 1);
assert.equal(state.targets[0].word, 'cat');
state = typeIntoGame(state, 'C');
assert.equal(state.locked, state.targets[0].key);
state = typeIntoGame(state, 'cx');
assert.equal(state.hits, 0);
state = typeIntoGame(state, 'c');
state = typeIntoGame(state, 'cat');
assert.equal(state.hits, 1);
assert.equal(state.targets.length, 0);
assert.equal(state.combo, 1);
assert.equal(state.score, 30);
assert(state.correct < state.typed, 'Wrong characters must reduce accuracy');
assert.equal(normalizeTyping('It’s'), "it's");
const paused = { ...state, phase: 'paused' as const };
assert.equal(typingTick(paused, 250, pool), paused);
assert.equal(typeIntoGame(paused, 'cat'), paused);
state = { ...state, targets: [{ ...pool[1], key: 12, lane: 1, y: 92.9 }], locked: 12, input: 'ca', spawnIn: 5000 };
state = typingTick(state, 100, pool);
assert.equal(state.lives, 2);
assert.equal(state.combo, 0);
assert.equal(state.input, '');
assert.equal(state.locked, null);
state = typingTick({ ...state, lives: 1, targets: [{ ...pool[2], key: 13, lane: 1, y: 92.9 }] }, 100, pool);
assert.equal(state.phase, 'finished');
assert.equal(typingTick(state, 100, pool), state);
assert.equal(typingTick({ ...newTypingGame(), elapsed: TYPING_DURATION - 100 }, 100, pool).phase, 'finished');
assert.equal(typingTick(newTypingGame(), 60_000, pool).elapsed, 250, 'Background timer catch-up must be capped');
const crowded = { ...newTypingGame(), targets: pool.map((word, key) => ({ ...word, key, lane: key % 3, y: 0 })) };
assert.equal(typingTick(crowded, 100, pool).targets.length, 5);
assert.equal(typingTick(crowded, 100, pool).serial, 0);
console.log('Typing game: target lock, correction, scoring, miss/lives, pause, duration and bounded tick/spawn passed.');
